//Number – a whole number or decimal value
var age=30;
console.log(typeof age)
console.log(age)
// String – text written using quotes or backticks
var courseName="Playwright Course"
console.log(typeof courseName)
console.log(courseName)

//Boolean – a value of true or false
var isPageLoaded=false
console.log(typeof isPageLoaded)
console.log(isPageLoaded)

//BigInt – a large integer written with the n suffix
var bigNumber =567n
console.log(typeof bigNumber)
console.log(bigNumber)

//Show an example of adding two BigInt values.
var bigNumber1 =567n
var bigNumber2=1n
var sum=bigNumber1+bigNumber2;
console.log(sum)
console.log(typeof sum)

//Undefined – a declared variable with no assigned value
var nameOfPerson;
console.log(typeof nameOfPerson)
console.log(nameOfPerson)

// Null – an intentional absence of a value
var unknownPerson =null;
console.log(unknownPerson)
console.log(typeof unknownPerson)


